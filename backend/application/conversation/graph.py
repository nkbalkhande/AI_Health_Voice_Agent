import asyncio
import re
from typing import Any

from langgraph.graph import END, StateGraph
from typing_extensions import TypedDict

from backend.application.conversation.understand import (
    UNDERSTAND_SYSTEM,
    parse_understanding,
)
from backend.application.knowledge.documents import DocumentKnowledgeBranch
from backend.application.knowledge.web import WebKnowledgeBranch
from backend.core.logger import logger
from backend.domain.entities.chunk import Chunk
from backend.domain.interfaces.cache import CacheStore
from backend.domain.interfaces.llm_provider import LLMProvider
from backend.domain.interfaces.web_search import WebDocument, WebSearchProvider
from backend.rag.retrieval.pipeline import RetrievalPipeline

log = logger.getChild("conversation.graph")


class ConversationState(TypedDict, total=False):
    session_id: str
    user_message: str
    history: list[dict[str, str]]
    summary: str
    facts: list[dict[str, Any]]
    filters: dict | None
    # Live voice turn: favour latency (no context compression).
    voice: bool
    intent: str
    standalone_query: str
    needs_retrieval: bool
    memory_updates: list[dict[str, Any]]
    updated_summary: str
    # Branch A and Branch B results. They stay separate on purpose:
    # nothing in this graph merges them into one list.
    rag_chunks: list[Chunk]
    web_documents: list[WebDocument]


class ConversationGraph:
    """One turn, drawn as the flow it runs:

        understand ─┬─> retrieve_documents (Branch A: RAG) ──┐
                    └─> retrieve_web       (Branch B: web) ──┴─> collect

    The two branches run in parallel and their results stay in separate
    state fields. The answer is generated by the caller so the same
    prepared evidence can be returned as a full reply or a token stream.
    """

    def __init__(
        self,
        *,
        llm: LLMProvider,
        pipeline: RetrievalPipeline,
        web_search: WebSearchProvider | None = None,
        cache: CacheStore | None = None,
        checkpointer_dsn: str | None = None,
        voice_understand_llm: LLMProvider | None = None,
    ) -> None:
        self._llm = llm
        self._voice_understand_llm = voice_understand_llm
        self._documents = DocumentKnowledgeBranch(pipeline)
        self._web = WebKnowledgeBranch(web_search, cache=cache)
        self._checkpointer_dsn = checkpointer_dsn
        self._checkpointed_graph = None
        # Voice turns start both searches on the raw words while the
        # understand step runs; kept only if the query was not rewritten.
        self._speculative: dict[str, dict[str, Any]] = {}
        self._graph = self._compile()

    async def warm_up(self) -> None:
        if self._checkpointer_dsn:
            await self._graph_with_checkpointer()

    async def run(self, state: ConversationState) -> ConversationState:
        thread_id = state.get("session_id")
        if thread_id and self._checkpointer_dsn:
            graph = await self._graph_with_checkpointer()
            if graph is not None:
                try:
                    return await graph.ainvoke(
                        state,
                        config={"configurable": {"thread_id": thread_id}},
                    )
                except Exception:
                    # Session rows in PostgreSQL are the durable record.
                    # A checkpoint failure must not lose the user's turn.
                    log.warning(
                        "LangGraph checkpointed run failed; retrying without it",
                        exc_info=True,
                    )
        return await self._graph.ainvoke(state)

    async def _graph_with_checkpointer(self):
        if self._checkpointed_graph is None:
            saver = await _shared_saver(self._checkpointer_dsn)
            if saver is None:
                return None
            self._checkpointed_graph = self._compile(saver)
        return self._checkpointed_graph

    def _compile(self, checkpointer=None):
        graph = StateGraph(ConversationState)
        graph.add_node("understand", self._understand)
        graph.add_node("retrieve_documents", self._retrieve_documents)
        graph.add_node("retrieve_web", self._retrieve_web)
        graph.add_node("collect", self._collect)
        graph.set_entry_point("understand")
        # Parallel branches: each writes only its own state field.
        graph.add_edge("understand", "retrieve_documents")
        graph.add_edge("understand", "retrieve_web")
        graph.add_edge("retrieve_documents", "collect")
        graph.add_edge("retrieve_web", "collect")
        graph.add_edge("collect", END)
        return graph.compile(checkpointer=checkpointer)

    async def _understand(self, state: ConversationState) -> dict[str, Any]:
        message = state.get("user_message") or ""
        history = state.get("history") or []
        summary = state.get("summary") or ""
        facts = state.get("facts") or []
        prompt = _understand_prompt(message, history, summary, facts)
        self._start_speculative(state)
        llm = (state.get("voice") and self._voice_understand_llm) or self._llm
        try:
            generation = await llm.chat(
                [
                    {"role": "system", "content": UNDERSTAND_SYSTEM},
                    {"role": "user", "content": prompt},
                ],
                max_tokens=500,
            )
        except BaseException:
            self._drop_speculative(state.get("session_id"))
            raise
        return parse_understanding(generation.text, message)

    def _search_query(self, state: ConversationState) -> str:
        return state.get("standalone_query") or state.get("user_message") or ""

    def _start_speculative(self, state: ConversationState) -> None:
        session_id = state.get("session_id")
        message = state.get("user_message") or ""
        if not (state.get("voice") and session_id and message.strip()):
            return
        self._drop_speculative(session_id)
        self._speculative[session_id] = {
            "query": _normalize(message),
            "documents": asyncio.create_task(
                self._documents.search(message, filters=state.get("filters"), compress=False)
            ),
            "web": asyncio.create_task(self._web.search(message)),
        }

    def _drop_speculative(self, session_id: str | None) -> None:
        entry = self._speculative.pop(session_id or "", None) or {}
        for key in ("documents", "web"):
            if key in entry:
                entry[key].cancel()

    async def _take_speculative(self, state: ConversationState, branch: str):
        """The branch's head-start result, or None if it does not apply."""
        session_id = state.get("session_id") or ""
        entry = self._speculative.get(session_id)
        if not entry or branch not in entry:
            return None
        task = entry.pop(branch)
        if "documents" not in entry and "web" not in entry:
            self._speculative.pop(session_id, None)
        usable = state.get("needs_retrieval", True) and (
            _normalize(self._search_query(state)) == entry["query"]
        )
        if not usable:
            task.cancel()
            return None
        return await task

    async def _retrieve_documents(self, state: ConversationState) -> dict[str, Any]:
        """Branch A only. Writes rag_chunks, nothing else."""
        speculative = await self._take_speculative(state, "documents")
        if speculative is not None:
            return {"rag_chunks": speculative}
        if not state.get("needs_retrieval", True):
            return {"rag_chunks": []}
        chunks = await self._documents.search(
            self._search_query(state),
            filters=state.get("filters"),
            compress=not state.get("voice", False),
        )
        return {"rag_chunks": chunks}

    async def _retrieve_web(self, state: ConversationState) -> dict[str, Any]:
        """Branch B only. Writes web_documents, nothing else."""
        speculative = await self._take_speculative(state, "web")
        if speculative is not None:
            return {"web_documents": speculative}
        if not state.get("needs_retrieval", True):
            return {"web_documents": []}
        pages = await self._web.search(self._search_query(state))
        return {"web_documents": pages}

    async def _collect(self, state: ConversationState) -> dict[str, Any]:
        """Join point. Both branches are done; their results stay separate."""
        return {}


# One saver per DSN for the whole process. Opening one takes seconds, and
# every chat or voice connection builds its own ConversationGraph. A DSN
# that failed maps to None so the failure is logged once, not every turn.
_SAVERS: dict[str, Any] = {}
_SAVER_CONTEXTS: list[Any] = []
_SAVER_LOCK: asyncio.Lock | None = None


async def _shared_saver(dsn: str):
    global _SAVER_LOCK
    if dsn in _SAVERS:
        return _SAVERS[dsn]
    _SAVER_LOCK = _SAVER_LOCK or asyncio.Lock()
    async with _SAVER_LOCK:
        if dsn not in _SAVERS:
            try:
                from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver

                context = AsyncPostgresSaver.from_conn_string(dsn)
                saver = await context.__aenter__()
                await saver.setup()
                _SAVER_CONTEXTS.append(context)
                _SAVERS[dsn] = saver
            except Exception:
                log.warning(
                    "LangGraph Postgres checkpointer unavailable; continuing "
                    "without it until restart",
                    exc_info=True,
                )
                _SAVERS[dsn] = None
    return _SAVERS[dsn]


def _normalize(text: str) -> str:
    return " ".join(re.sub(r"[^\w\s]", " ", text.lower()).split())


def _understand_prompt(
    message: str,
    history: list[dict[str, str]],
    summary: str,
    facts: list[dict[str, Any]],
) -> str:
    lines = []
    if summary:
        lines.append(f"Session summary:\n{summary}")
    if facts:
        rendered = "\n".join(
            f"- {item.get('key')}: {item.get('value')}"
            for item in facts
            if isinstance(item, dict)
        )
        if rendered:
            lines.append(f"Known facts:\n{rendered}")
    if history:
        transcript = "\n".join(
            f"{item.get('role', 'user')}: {item.get('content', '')}"
            for item in history[-12:]
        )
        lines.append(f"Recent turns:\n{transcript}")
    lines.append(f"Latest message:\n{message}")
    return "\n\n".join(lines)
